export default defineConfig({
  plugins: [vue(), tailwindcss()],
  define: {
    __APP_VERSION__: JSON.stringify(pkg.version),
  },
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  server: {
    port: 3100,
    host: true,
    proxy: {
      '/api': `http://localhost:${process.env.GINKGO_API_PORT ?? 3101}`,
    },
  },
})
