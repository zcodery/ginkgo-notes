export type IconKind = 'emoji' | 'lucide' | 'asset' | 'url' | 'empty'

export interface ParsedIcon {
  kind: IconKind
  /** emoji 字符 / lucide 名 / asset id / url */
  value: string
  /** 写入 page.icon 的原始字符串 */
  raw: string
}

export function parsePageIcon(icon: string | null | undefined): ParsedIcon {
  const raw = (icon ?? '').trim()
  if (!raw) return { kind: 'empty', value: '', raw: '' }
  if (raw.startsWith('lucide:')) return { kind: 'lucide', value: raw.slice(7), raw }
  if (raw.startsWith(ASSET_PREFIX)) return { kind: 'asset', value: raw.slice(ASSET_PREFIX.length), raw }
  if (/^https?:\/\//i.test(raw)) return { kind: 'url', value: raw, raw }
  return { kind: 'emoji', value: raw, raw }
}

export function emojiIcon(emoji: string) {
  return emoji
}
export function lucideIcon(name: string) {
  return `lucide:${name}`
}
export function assetIcon(id: string) {
  return `${ASSET_PREFIX}${id}`
}
export function urlIcon(url: string) {
  return url.trim()
}

