/* ---------------- 最近使用 ---------------- */

const RECENT_KEY = 'recentPageIcons'
const RECENT_LIMIT = 24

export async function loadRecentIcons(): Promise<string[]> {
  const list = await getMeta<string[]>(RECENT_KEY, [])
  return Array.isArray(list) ? list.filter((x) => typeof x === 'string') : []
}

export async function pushRecentIcon(icon: string): Promise<string[]> {
  if (!icon) return loadRecentIcons()
  const prev = await loadRecentIcons()
  const next = [icon, ...prev.filter((x) => x !== icon)].slice(0, RECENT_LIMIT)
  await setMeta(RECENT_KEY, next)
  return next
}
